"""Inventory of the four Qualtrics CSV exports in data/raw/ (survey-followups audit, step 1).

For every column: its position (v###, the id survey_spec.py uses), the question text, how many completed responses
answered it, how many distinct answers there are, and which model variable reads it (blank = never read). Writes
docs/survey_audit/inventory.md. Only question wording and counts are written — never any respondent's answers.

    python scripts/survey_inventory.py
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from ucsim.ingest.survey_spec import SPEC  # noqa: E402
from ucsim.ingest.surveys import _csv_responses, raw_path  # noqa: E402

SKIP = ("StartDate", "EndDate", "Status", "IPAddress", "Progress", "Duration", "Finished", "RecordedDate", "ResponseId",
        "RecipientLastName", "RecipientFirstName", "RecipientEmail", "ExternalReference", "LocationLatitude",
        "LocationLongitude", "DistributionChannel", "UserLanguage")


def main():
    import csv
    out = ["# Survey inventory (survey-followups audit, step 1)", "",
           "Generated by `scripts/survey_inventory.py` from the raw exports in `data/raw/` (not committed). Question",
           "wording and counts only. *read by* = the model variable that reads the column (blank = never read);",
           "*distinct* > 40 usually means free text.", ""]
    for slug, spec in SPEC.items():
        path = raw_path(slug)
        if path is None or path.suffix != ".csv":
            out += [f"## {spec['title']} — no CSV export in data/raw/", ""]
            continue
        with path.open(newline="", encoding="utf-8-sig") as f:
            header = next(csv.reader(f))
        resp = [r for r in _csv_responses(path) if r["completed"]]
        answered, values = {}, {}
        for r in resp:
            for a in r["answers"]:
                q = a["question_id"]
                answered[q] = answered.get(q, 0) + 1
                values.setdefault(q, set()).add(a["answer_value"])
        used = spec["vars"]
        n_unused = sum(1 for j, h in enumerate(header) if f"v{j:03d}" not in used and h not in SKIP)
        out += [f"## {spec['title']} ({slug}) — {len(resp)} completed responses, {len(header)} columns, "
                f"{n_unused} substantive columns never read", "",
                "| id | question | answered | distinct | read by |", "|---|---|---|---|---|"]
        for j, h in enumerate(header):
            if h in SKIP:
                continue
            q = f"v{j:03d}"
            name = used[q][0] if q in used else ""
            text = " ".join(h.split())[:140].replace("|", "/")
            out.append(f"| {q} | {text} | {answered.get(q, 0)} | {len(values.get(q, ()))} | {name} |")
        out.append("")
    dst = ROOT / "docs" / "survey_audit" / "inventory.md"
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text("\n".join(out), encoding="utf-8")
    print("wrote", dst)


if __name__ == "__main__":
    main()
